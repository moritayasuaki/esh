use esh_host::HostError;
use esh_lang::compiler::Source;
use std::{path::PathBuf, process::Command, time::Duration};
use tiny_http::{Header, Response, Server, StatusCode};

fn workspace() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .to_owned()
}
fn assets() -> PathBuf {
    std::env::var_os("ESH_WEB_DIST")
        .map(PathBuf::from)
        .unwrap_or_else(|| workspace().join(".local/web"))
}
pub fn build() -> Result<(), HostError> {
    let root = workspace();
    let dist = assets();
    std::fs::create_dir_all(&dist)?;
    let status = Command::new("cargo")
        .args([
            "build",
            "--locked",
            "--release",
            "-p",
            "esh-web",
            "--target",
            "wasm32-unknown-unknown",
        ])
        .current_dir(&root)
        .status()?;
    if !status.success() {
        return Err(HostError::new("web-build", "Rust/Wasm compilation failed."));
    }
    let local = root.join(".local/wasm-tools/bin/wasm-bindgen");
    let generator = std::env::var_os("WASM_BINDGEN")
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            if local.is_file() {
                local
            } else {
                PathBuf::from("wasm-bindgen")
            }
        });
    let status = Command::new(generator)
        .arg(root.join("target/wasm32-unknown-unknown/release/esh_web.wasm"))
        .args(["--target", "web", "--no-typescript", "--out-dir"])
        .arg(&dist)
        .status()?;
    if !status.success() {
        return Err(HostError::new(
            "web-build",
            "Wasm binding generation failed.",
        ));
    }
    std::fs::write(dist.join("bootstrap.js"),"// Generated by esh build-web; application logic is Rust/Wasm.\nimport init from './esh_web.js';\nawait init();\n")?;
    println!("Built Rust/Wasm editor assets. Start it with: esh serve examples/config-update.esh");
    Ok(())
}
pub fn serve(
    sources: Vec<Source>,
    initial_state: Option<String>,
    port: u16,
) -> Result<(), HostError> {
    let dist = assets();
    if !dist.join("esh_web_bg.wasm").is_file() {
        return Err(HostError::new(
            "web-build-required",
            "Run 'cargo run -p esh-cli -- build-web' first.",
        ));
    }
    let server = Server::http(("127.0.0.1", port))
        .map_err(|_| HostError::new("server", "Could not bind the loopback editor port."))?;
    let address = server
        .server_addr()
        .to_ip()
        .ok_or_else(|| HostError::new("server", "Expected a TCP address."))?;
    let host = address.to_string();
    let origin = format!("http://{host}");
    let project =
        serde_json::to_vec(&serde_json::json!({"sources":sources,"initialState":initial_state}))
            .map_err(|_| HostError::new("server", "Cannot encode project snapshot."))?;
    println!("Rust/Wasm editor: {origin}/");
    loop {
        let Some(request) = server
            .recv_timeout(Duration::from_secs(1))
            .map_err(|_| HostError::new("server", "Could not receive a local request."))?
        else {
            continue;
        };
        let actual_host = request
            .headers()
            .iter()
            .find(|h| h.field.equiv("Host"))
            .map(|h| h.value.as_str())
            .unwrap_or("");
        let actual_origin = request
            .headers()
            .iter()
            .find(|h| h.field.equiv("Origin"))
            .map(|h| h.value.as_str());
        let authorized = actual_host == host
            && actual_origin.is_none_or(|o| o == origin)
            && request.method().as_str() == "GET";
        let (status, content_type, bytes) = if !authorized {
            (403, "text/plain", b"Request rejected.".to_vec())
        } else {
            match request.url() {
                "/" | "/index.html" => (
                    200,
                    "text/html; charset=utf-8",
                    include_bytes!("../../esh-web/index.html").to_vec(),
                ),
                "/style.css" => (
                    200,
                    "text/css; charset=utf-8",
                    include_bytes!("../../esh-web/style.css").to_vec(),
                ),
                "/api/project" => (200, "application/json; charset=utf-8", project.clone()),
                path @ ("/bootstrap.js" | "/esh_web.js" | "/esh_web_bg.wasm") => {
                    match std::fs::read(dist.join(&path[1..])) {
                        Ok(bytes) => (
                            200,
                            if path.ends_with(".wasm") {
                                "application/wasm"
                            } else {
                                "text/javascript; charset=utf-8"
                            },
                            bytes,
                        ),
                        Err(_) => (404, "text/plain", b"Build artifact unavailable.".to_vec()),
                    }
                }
                _ => (404, "text/plain", b"Not found.".to_vec()),
            }
        };
        let mut response = Response::from_data(bytes).with_status_code(StatusCode(status));
        for(name,value)in[("Content-Type",content_type),("Cache-Control","no-store"),("X-Content-Type-Options","nosniff"),("Content-Security-Policy","default-src 'self'; script-src 'self' 'wasm-unsafe-eval'; style-src 'self'; connect-src 'self'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'")]{response.add_header(Header::from_bytes(name,value).unwrap());}
        let _ = request.respond(response);
    }
}
